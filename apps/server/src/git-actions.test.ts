import { strict as assert } from "node:assert";
import { mkdtemp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { test } from "node:test";
import { checkoutRemoteBranch, commitChanges, createBranch, getPushTarget, localBranches, pushBranch, remoteBranches, runGit, switchBranch, syncRemote } from "./git-actions.ts";

test("switches local branches and commits repository-wide changes", async () => {
  const dir = await mkdtemp(join(tmpdir(), "pi-web-git-"));
  try {
    const repo = join(dir, "repo");
    const remote = join(dir, "remote.git");
    await mkdir(repo);
    await runGit(dir, "init", "--bare", remote);
    await runGit(repo, "init", "-b", "main");
    await runGit(repo, "config", "user.name", "Test");
    await runGit(repo, "config", "user.email", "test@example.com");
    await writeFile(join(repo, "file"), "first\n");
    await commitChanges(repo, "initial");
    await runGit(repo, "remote", "add", "origin", remote);
    await runGit(repo, "push", "-u", "origin", "main");
    await writeFile(join(repo, "file"), "uncommitted\n");
    await createBranch(repo, "feature/example", "main");
    assert.equal((await runGit(repo, "branch", "--show-current")).trim(), "feature/example");
    assert.equal(await readFile(join(repo, "file"), "utf8"), "uncommitted\n");
    await assert.rejects(createBranch(repo, "--force", "feature/example"));
    await assert.rejects(createBranch(repo, "invalid..name", "feature/example"));
    await assert.rejects(createBranch(repo, "wrong-base", "main"), /changed/);
    await assert.rejects(createBranch(repo, "main", "feature/example"));
    await switchBranch(repo, "main");
    await runGit(repo, "restore", "file");
    await runGit(repo, "branch", "other");
    assert.deepEqual(await localBranches(repo), ["feature/example", "main", "other"]);
    await switchBranch(repo, "other");
    await assert.rejects(switchBranch(repo, "--orphan"), /Unknown local branch/);
    await mkdir(join(repo, "nested"));
    await writeFile(join(repo, "file"), "second\n");
    await writeFile(join(repo, "nested", "new"), "new\n");
    await commitChanges(join(repo, "nested"), "second");
    assert.equal((await runGit(repo, "status", "--porcelain")).trim(), "");
    assert.equal(await readFile(join(repo, "file"), "utf8"), "second\n");
    const target = await getPushTarget(repo);
    assert.ok(target);
    assert.equal(target.hasUpstream, false);
    assert.equal(target.ref, "refs/heads/other");
    await assert.rejects(pushBranch(repo, { ...target, branch: "wrong" }), /target changed/);
    await pushBranch(repo, target);
    const upstream = await getPushTarget(repo);
    assert.ok(upstream);
    assert.equal(upstream.hasUpstream, true);
    assert.equal(upstream.ahead, 0);
    await writeFile(join(repo, "file"), "third\n");
    await commitChanges(repo, "third");
    const ahead = await getPushTarget(repo);
    assert.ok(ahead);
    assert.equal(ahead.ahead, 1);
    const hook = join(remote, "hooks", "pre-receive");
    await writeFile(hook, "#!/bin/sh\nexit 1\n", { mode: 0o755 });
    await assert.rejects(pushBranch(repo, ahead));
    assert.equal((await getPushTarget(repo))?.ahead, 1);
    await rm(hook);
    await pushBranch(repo, ahead);
    assert.equal((await getPushTarget(repo))?.ahead, 0);
    const peer = join(dir, "peer");
    await runGit(dir, "clone", "--branch", "other", remote, peer);
    await runGit(peer, "config", "user.name", "Test");
    await runGit(peer, "config", "user.email", "test@example.com");
    await writeFile(join(peer, "remote-file"), "remote\n");
    await commitChanges(peer, "remote update");
    await runGit(peer, "push");
    const beforeFetch = await getPushTarget(repo);
    assert.ok(beforeFetch);
    await syncRemote(repo, "fetch", beforeFetch);
    const behind = await getPushTarget(repo);
    assert.ok(behind);
    assert.equal(behind.behind, 1);
    await syncRemote(repo, "pull", behind);
    assert.equal(await readFile(join(repo, "remote-file"), "utf8"), "remote\n");
    await writeFile(join(repo, "local-only"), "local\n");
    await commitChanges(repo, "local update");
    await writeFile(join(peer, "remote-file"), "second remote\n");
    await commitChanges(peer, "second remote update");
    await runGit(peer, "push");
    const beforeDivergedFetch = await getPushTarget(repo);
    assert.ok(beforeDivergedFetch);
    await syncRemote(repo, "fetch", beforeDivergedFetch);
    const diverged = await getPushTarget(repo);
    assert.ok(diverged);
    assert.equal(diverged.ahead, 1);
    assert.equal(diverged.behind, 1);
    await assert.rejects(syncRemote(repo, "pull", diverged));
    assert.equal(await readFile(join(repo, "local-only"), "utf8"), "local\n");
    await assert.rejects(syncRemote(repo, "fetch", { ...diverged, remote: "unknown" }), /target changed/);
    await assert.rejects(commitChanges(repo, "  "), /required/);
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
});

test("checks out a remote branch with tracking without overwriting local work", async () => {
  const dir = await mkdtemp(join(tmpdir(), "pi-web-remote-"));
  try {
    const remote = join(dir, "remote.git");
    const source = join(dir, "source");
    const client = join(dir, "client");
    await mkdir(source);
    await runGit(dir, "init", "--bare", remote);
    await runGit(source, "init", "-b", "main");
    await runGit(source, "config", "user.name", "Test");
    await runGit(source, "config", "user.email", "test@example.com");
    await writeFile(join(source, "file"), "main\n");
    await commitChanges(source, "initial");
    await runGit(source, "remote", "add", "origin", remote);
    await runGit(source, "push", "-u", "origin", "main");
    await createBranch(source, "feature/remote", "main");
    await writeFile(join(source, "file"), "remote\n");
    await commitChanges(source, "remote change");
    await runGit(source, "push", "-u", "origin", "feature/remote");
    await runGit(dir, "clone", "--branch", "main", remote, client);
    const refs = await remoteBranches(client);
    const remoteRef = refs.find((branch) => branch.name === "origin/feature/remote");
    assert.ok(remoteRef);
    assert.equal(refs.some((branch) => branch.name === "origin/HEAD"), false);
    await assert.rejects(checkoutRemoteBranch(client, "refs/heads/main"), /not found/);
    await writeFile(join(client, "file"), "unsaved\n");
    await assert.rejects(checkoutRemoteBranch(client, remoteRef.ref));
    assert.equal(await readFile(join(client, "file"), "utf8"), "unsaved\n");
    await runGit(client, "restore", "file");
    await checkoutRemoteBranch(client, remoteRef.ref);
    assert.equal((await runGit(client, "branch", "--show-current")).trim(), "feature/remote");
    assert.equal((await runGit(client, "rev-parse", "--abbrev-ref", "@{upstream}")).trim(), "origin/feature/remote");
    await assert.rejects(checkoutRemoteBranch(client, remoteRef.ref), /already exists/);
  } finally { await rm(dir, { recursive: true, force: true }); }
});
